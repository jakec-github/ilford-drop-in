#!/bin/bash
#
# Start one environment's app on the droplet and prove it answers.
#
# Usage (on the droplet): bash /opt/dropin/rollout.sh <prod|preprod> [image-tag]
#
# Everything that starts an app container goes through here — the deploy
# workflow for preprod and the production workflow for prod (each with a tag),
# scripts/deploy-config.sh after shipping a config, and
# scripts/preprod.sh up (both without one) — so there is one place that knows
# which service an environment is, where its tag is recorded, and what counts
# as it being up. The deploy workflow copies it to /opt/dropin beside
# compose.yaml and the Caddyfile.
#
# It:
#   - waits for any other rollout on the box to finish first;
#   - does nothing, with a notice, while env/<env>/disabled exists
#     (scripts/preprod.sh down);
#   - records the tag, if given, in env/<env>/image.env and rebuilds .env from
#     every environment's file (see deploy/compose.yaml for why);
#   - recreates that environment's container and no other, and fails if the
#     other environment's container changed;
#   - waits for https://<its domain>/health, the domain read from site.env, and
#     on a timeout exits non-zero with the app's logs.
#
# Run with GITHUB_ACTIONS=true and the skip notice is an Actions annotation.

set -euo pipefail

cd "$(dirname "$0")"

usage() {
    echo "Usage: $0 <prod|preprod> [image-tag]" >&2
    exit 2
}

[[ $# -ge 1 && $# -le 2 ]] || usage
ENV="$1"
TAG="${2:-}"

case "$ENV" in
    prod)
        SERVICE=app
        OTHER_SERVICE=app-preprod
        TAG_VAR=PROD_IMAGE_TAG
        DOMAIN_VAR=SITE_DOMAIN
        ;;
    preprod)
        SERVICE=app-preprod
        OTHER_SERVICE=app
        TAG_VAR=PREPROD_IMAGE_TAG
        DOMAIN_VAR=PREPROD_DOMAIN
        ;;
    *) usage ;;
esac

ENV_DIR="env/${ENV}"
TAG_FILE="${ENV_DIR}/image.env"
READY_TIMEOUT_SECONDS="${ROLLOUT_TIMEOUT:-120}"

fail() {
    echo "" >&2
    echo "$ENV: $*" >&2
    exit 1
}

# One rollout at a time, whichever of the deploy workflow, the production
# workflow, deploy-config.sh or preprod.sh started it: each ends by pruning
# every image no container uses, which can remove the image another is about to
# start. A lock here covers all four, where a concurrency group in Actions
# would cover only the workflows — and would cancel a queued production deploy
# when a merge queued behind it.
exec 9>.rollout.lock
if ! flock -w "${ROLLOUT_LOCK_TIMEOUT:-600}" 9; then
    fail "another rollout has held /opt/dropin/.rollout.lock for ${ROLLOUT_LOCK_TIMEOUT:-600}s"
fi

mkdir -p "$ENV_DIR"

# Switched off: leave everything as it is, including the recorded tag, so that
# `scripts/preprod.sh up` brings back the image it last ran rather than one it
# never did.
if [[ -f "${ENV_DIR}/disabled" ]]; then
    message="${ENV} is switched off (${ENV_DIR}/disabled), so it was not deployed. scripts/preprod.sh up brings it back."
    if [[ "${GITHUB_ACTIONS:-}" == true ]]; then
        echo "::notice title=${ENV} skipped::${message}"
    else
        echo "$message"
    fi
    exit 0
fi

# Work out what to poll before changing anything, so a box missing its domain
# says so without having touched a container.
if [[ ! -f site.env ]]; then
    fail "/opt/dropin/site.env not found — see docs/deployment.md"
fi
domain="$(
    # shellcheck disable=SC1091
    . ./site.env
    echo "${!DOMAIN_VAR:-}"
)"
if [[ -z "$domain" ]]; then
    fail "${DOMAIN_VAR} is empty or unset in /opt/dropin/site.env, so there is no host to check it on. Set it, or switch ${ENV} off."
fi
health="https://${domain}/health"

if [[ -n "$TAG" ]]; then
    echo "${TAG_VAR}=${TAG}" >"$TAG_FILE"
fi
if [[ ! -f "$TAG_FILE" ]]; then
    fail "no image recorded in ${TAG_FILE}: run the deploy workflow to deploy one"
fi

# Compose interpolates from .env alone, so it is rebuilt from every
# environment's tag file, each written only by that environment's rollouts.
{
    echo "# Generated by rollout.sh from env/*/image.env — edit those, not this."
    for file in env/*/image.env; do
        [[ -f "$file" ]] && cat "$file"
    done
} >.env

other_before="$(docker compose ps -aq "$OTHER_SERVICE")"

echo "Deploying ${ENV}: $(cat "$TAG_FILE")"
# Caddy is started here, for a fresh box, but never deliberately recreated:
# `up -d caddy` is a no-op while it runs and its compose definition is
# unchanged. So a new Caddyfile or site.env reaches it only through
# `docker compose up -d --force-recreate caddy` (docs/deployment.md).
docker compose up -d caddy
# --force-recreate: a config shipped by deploy-config.sh changes nothing compose
# can see, so without it the container would keep the file it started with.
docker compose up -d --force-recreate "$SERVICE"

echo ""
echo "Waiting for ${health}..."
deadline=$((SECONDS + READY_TIMEOUT_SECONDS))
until curl -fs -o /dev/null --max-time 5 "$health"; do
    if ((SECONDS >= deadline)); then
        echo "" >&2
        echo "Last 50 lines of the ${SERVICE} log:" >&2
        docker compose logs --tail=50 --no-color "$SERVICE" >&2 || true
        fail "${health} did not answer within ${READY_TIMEOUT_SECONDS}s"
    fi
    sleep 2
done
echo "${ENV} is answering on ${health}"

other_after="$(docker compose ps -aq "$OTHER_SERVICE")"
if [[ "$other_before" != "$other_after" ]]; then
    fail "deploying ${ENV} replaced the ${OTHER_SERVICE} container (${other_before:-none} → ${other_after:-none})"
fi
echo "${OTHER_SERVICE} untouched: ${other_after:-not running}"

# `prune -a`, not `prune`: every image here is tagged with its commit, so none
# is ever dangling, and plain prune left each deploy's image behind until the
# disk filled (#223). -a removes every image no container uses; a rollback or
# `scripts/preprod.sh up` pulls its image back from ghcr, which is public.
docker image prune -af >/dev/null
